    // Ключевые слова настроений. \b в Java не дружит с кириллицей, поэтому границы слова — через lookaround.
    private const val L = "a-zа-яё0-9"
    private fun words(vararg w: String) = "(?<![$L])(?:${w.joinToString("|")})(?![$L])"

    val keywords: List<Pair<String, Regex>> = listOf(
        "love" to Regex("❤|♥|💕|💖|😘|😍|🥰|" + words("люблю", "обнима[а-яё]*", "целую", "love"), RegexOption.IGNORE_CASE),
        "angry" to Regex(
            "😡|🤬|💢|" + words(
