        "laugh" to Regex("(?:ха){2,}|(?:хе){2,}|(?:хи){2,}|😂|🤣|" + words("лол", "lol", "ржу[а-яё]*"), RegexOption.IGNORE_CASE),
        "hi" to Regex(words("привет[а-яё]*", "здравствуй[а-яё]*", "хай", "салют", "hello", "hi", "hey"), RegexOption.IGNORE_CASE),
    )

    fun match(text: String): String? {
        val t = text.take(400)
        return keywords.firstOrNull { it.second.containsMatchIn(t) }?.first
    }

    fun pick(category: String, name: String?, last: String?): String {
        var list = phrases[category] ?: listOf(category)
        if (name == null) list = list.filter { "{name}" !in it }.ifEmpty { list }
        val options = list.filter { it != last }.ifEmpty { list }
        return options.random().replace("{name}", name ?: "")
    }
